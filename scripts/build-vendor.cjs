"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const vendor = path.join(root, "assets", "vendor");
fs.mkdirSync(vendor, { recursive: true });
for (const [source, target] of [
  ["three/build/three.min.js", "three.min.js"],
  ["three/LICENSE", "THREE-LICENSE.txt"],
  ["lucide-static/LICENSE", "LUCIDE-LICENSE.txt"],
]) {
  fs.copyFileSync(path.join(root, "node_modules", source), path.join(vendor, target));
}
const icons = {};
const dir = path.join(root, "node_modules", "lucide-static", "icons");
for (const file of fs.readdirSync(dir).filter((file) => file.endsWith(".svg")).sort()) {
  const svg = fs.readFileSync(path.join(dir, file), "utf8");
  const inner = svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/);
  if (!inner || /<script|on\w+=|href=|url\(/i.test(inner[1]))
    throw new Error(`Unexpected markup in Lucide icon ${file}`);
  icons[file.slice(0, -4)] = inner[1].trim();
}
fs.writeFileSync(path.join(root, "src", "elements.js"),
  '/* Lucide 0.468.0 - ISC; see assets/vendor/LUCIDE-LICENSE.txt. Generated by build:vendor. */\n' +
  '(function(root){const icons=' + JSON.stringify(icons) +
  ';if(typeof module==="object"&&module.exports)module.exports=icons;else root.MotionElements=icons;})(globalThis);\n');
console.log(`Bundled Three.js 0.160.1 and ${Object.keys(icons).length} Lucide elements.`);
